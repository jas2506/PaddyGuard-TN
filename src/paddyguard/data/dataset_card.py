"""Render reports/dataset_card.md from the manifest and the checks (M1)."""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any

import pandas as pd

from paddyguard.data.download import Check

NOT_CHECKED = "NOT YET CHECKED (copy the licence text from the dataset page into configs/data.yaml)"
TOP_SIZES = 3
# card section -> (manifest dataset code, config key of the dataset, config key of its licence)
SECTIONS = [("S", "S", "S"), ("T1", "T1", "T1"), ("T2", "T2", "T2")]


def _table(header: list[str], rows: list[list[Any]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def _size_summary(df: pd.DataFrame) -> str:
    sizes = (df["width"].astype(str) + "×" + df["height"].astype(str)).value_counts()
    top = ", ".join(f"{s} ({n})" for s, n in sizes.head(TOP_SIZES).items())
    return (
        f"width {df['width'].min()}–{df['width'].max()} (median {df['width'].median():g}), "
        f"height {df['height'].min()}–{df['height'].max()} (median {df['height'].median():g}); "
        f"most common sizes: {top}"
    )


def _dataset_section(code: str, df: pd.DataFrame, cfg: Mapping[str, Any]) -> str:
    sub = df[df["dataset"] == code]
    ds = cfg["datasets"][code]
    parts = [f"## {code}: {ds['name']}", f"Source: {ds['source']}", f"Images: {len(sub)}"]
    counts = sub["label_raw"].value_counts().sort_index()
    if code == "T2":
        by_bg = sub.groupby(["background", "label_raw"]).size().reset_index(name="n")
        parts.append(
            _table(["background", "class folder (as shipped)", "images"], by_bg.values.tolist())
        )
    else:
        parts.append(
            _table(["class folder (as shipped)", "images"], counts.reset_index().values.tolist())
        )
    parts.append(f"Image sizes: {_size_summary(sub)}")
    return "\n\n".join(parts)


def render_dataset_card(df: pd.DataFrame, checks: list[Check], cfg: Mapping[str, Any]) -> str:
    out = [
        "# Dataset card",
        "Generated by `python -m paddyguard.data.manifest`. Do not edit by hand.",
    ]
    for code, ds_key, _ in SECTIONS:
        out.append(_dataset_section(code, df, cfg))
    seg = cfg["datasets"]["RiceSeg"]
    out.append(
        f"## RiceSeg: {seg['name']}\n\nSource: {seg['source']}\n\n"
        f"Masks paired with Sethy images: {int(df['mask_path'].notna().sum())}"
    )
    licences = [
        [k, cfg["datasets"][k]["name"], cfg["licences"].get(k) or NOT_CHECKED]
        for k in ("S", "T1", "RiceSeg", "T2")
    ]
    out.append("## Licences\n\n" + _table(["code", "dataset", "licence text"], licences))
    out.append(
        "## Checks\n\n"
        + _table(
            ["check", "result", "detail"],
            [[c.name, "ok" if c.ok else "**FAIL**", c.detail] for c in checks],
        )
    )
    return "\n\n".join(out) + "\n"
